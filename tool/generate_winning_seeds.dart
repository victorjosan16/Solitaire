// Generates lib/features/solitaire/domain/engine/verified_seeds.dart.
//
//   dart run tool/generate_winning_seeds.dart [draw1Count] [draw3Count]
//
// A seed is only accepted when the solver produces a concrete solution AND
// that solution is replayed move-by-move through KlondikeEngine to a win.
import 'dart:io';

import 'package:solitaire_nova/features/solitaire/domain/engine/klondike_engine.dart';
import 'package:solitaire_nova/features/solitaire/domain/engine/solver.dart';
import 'package:solitaire_nova/features/solitaire/domain/models/game_config.dart';

List<int> find(GameConfig config, int count, int startSeed) {
  final out = <int>[];
  var seed = startSeed;
  var tried = 0;
  final sw = Stopwatch()..start();
  while (out.length < count) {
    seed = (seed * 1103515245 + 12345) & 0x7FFFFFFF; // spread seeds
    tried++;
    final r = KlondikeSolver(maxNodes: 60000).solveSeed(seed, config);
    if (!r.solved) continue;
    var s = KlondikeEngine.dealSeed(seed, config);
    for (final m in r.solution!) {
      s = KlondikeEngine.apply(s, m).state;
    }
    if (!s.isWon) throw StateError('replay failed for $seed');
    out.add(seed);
  }
  stderr.writeln('draw${config.drawCount}: ${out.length}/$tried solved '
      'in ${sw.elapsed.inSeconds}s');
  return out;
}

void main(List<String> args) {
  final n1 = args.isNotEmpty ? int.parse(args[0]) : 400;
  final n3 = args.length > 1 ? int.parse(args[1]) : 200;
  final d1 = find(GameConfig.draw1, n1, 20250101);
  final d3 = find(GameConfig.draw3, n3, 20250303);
  String fmt(List<int> l) {
    final b = StringBuffer();
    for (var i = 0; i < l.length; i += 6) {
      b.writeln('  ${l.skip(i).take(6).join(', ')},');
    }
    return b.toString();
  }

  File('lib/features/solitaire/domain/engine/verified_seeds.dart')
      .writeAsStringSync('''
// GENERATED by tool/generate_winning_seeds.dart — do not edit by hand.
//
// Every seed below was solved by KlondikeSolver (unlimited recycles,
// foundation-to-tableau allowed) and the solution was replayed through
// KlondikeEngine to a win. test/unit/engine/verified_seeds_test.dart
// re-verifies a sample on every CI run.

/// Verified winnable Draw-1 deals (also used for Daily Challenges).
const List<int> verifiedDraw1Seeds = <int>[
${fmt(d1)}];

/// Verified winnable Draw-3 deals.
const List<int> verifiedDraw3Seeds = <int>[
${fmt(d3)}];
''');
}
